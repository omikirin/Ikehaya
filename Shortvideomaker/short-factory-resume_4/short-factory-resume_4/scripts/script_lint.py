def texts_from(path: Path):
    if path.suffix == ".json":
        spec = json.loads(path.read_text())
        for seg in spec.get("segments", []):
            yield seg.get("id", "?"), seg.get("text", "")
    else:
        for i, line in enumerate(path.read_text().splitlines(), 1):
            if line.strip():
                yield f"L{i}", line

def scan(text, accepts):
    """スパンマスクつき照合: 長い表面形を先に取り、重なる短い語の二重報告を防ぐ
    (例:「大人気」が人気にも重複ヒットしない)。返り値=[(level, surface, info)]"""
    pats = [("BLOCK", p, i) for p, i in HETERONYMS.items()] + \
           [("WARN", p, i) for p, i in MISREADS.items()]
    pats.sort(key=lambda x: -len(x[1]))
    taken, found = set(), []
    for level, pat, info in pats:
        for m in re.finditer(pat, text):
            span = set(range(m.start(), m.end()))
            if span & taken or m.group(0) in accepts:
                continue
            taken |= span
            found.append((level, m.group(0), info))
    return found

def main(argv):
    files, accepts, strict = [], set(), False
    it = iter(argv)
    for a in it:
        if a == "--accept":
            accepts.add(next(it))
        elif a == "--strict":
            strict = True
        else:
            files.append(Path(a))
    if not files:
        sys.exit(__doc__)
    blocks = warns = 0
    for f in files:
        for sid, text in texts_from(f):
            for level, surface, (yomi, advice) in scan(text, accepts):
                mark = "⚠️" if level == "BLOCK" else "🟡"
                if level == "BLOCK":
                    blocks += 1
                else:
                    warns += 1
                print(f"{mark} {f.name} {sid}: 「{surface}」({yomi})")
                print(f"   {text.strip()[:60]}")
                print(f"   → {advice}")
    if blocks or warns:
        print(f"\n⚠️ブロック{blocks}件 / 🟡実績警告{warns}件。"
              "表記を固定するか、読みが一意と裁定した語だけ --accept で通す")
    else:
        print("✅ 読み事故リスクなし")
    if blocks or (strict and warns):
        sys.exit(1)

if __name__ == "__main__":
    main(sys.argv[1:])
